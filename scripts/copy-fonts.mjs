// 构建前：把自托管的 Noto Sans JP（400/700）复制到 public/fonts 并生成合并 CSS（运行时非阻塞加载）。
import fs from "node:fs";
import path from "node:path";

const src = "node_modules/@fontsource/noto-sans-jp";
const out = "public/fonts/noto-sans-jp";
fs.mkdirSync(out, { recursive: true });
let css = "/* Noto Sans JP (SIL OFL 1.1) — generated by scripts/copy-fonts.mjs */\n";
for (const w of ["400", "700"]) {
  const text = fs.readFileSync(path.join(src, `${w}.css`), "utf8");
  css += text.replace(/url\(\.\/files\/([^)]+)\)/g, (_, f) => {
    if (f.endsWith(".woff2")) fs.copyFileSync(path.join(src, "files", f), path.join(out, f));
    return `url(/fonts/noto-sans-jp/${f})`;
  }).replace(/,\s*url\([^)]+\.woff\)\s*format\('woff'\)/g, "")
    // optional：首次访问若字体未及时就绪就沿用系统字体、不中途替换（避免推迟 LCP / 重排）；缓存后下次访问即使用
    .replace(/font-display:\s*swap/g, "font-display: optional");
}
fs.writeFileSync("public/fonts/noto-sans-jp.css", css);
console.log(`fonts: ${fs.readdirSync(out).length} files`);

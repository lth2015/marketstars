/** 按当前语言返回业务错误的显示文案。 */
export async function bizErrorText(e: { code: string; message: string }): Promise<string> {
  if ((await getLocale()) !== "en") return e.message;
  return EN_BY_TEXT[e.message] ?? EN_BY_CODE[e.code] ?? "The request could not be completed. Please try again.";
}
